export function filterFunctionCategories(functionCategories, query = '') {
  const normalizedQuery = query.trim().toLowerCase();
  if (!normalizedQuery) return functionCategories;

  return functionCategories
    .map((category) => ({
      ...category,
      functions: category.functions.filter((item) =>
        [
          item.name,
          item.signature,
          item.description,
          item.details,
          category.title,
        ]
          .join(' ')
          .toLowerCase()
          .includes(normalizedQuery),
      ),
    }))
    .filter((category) => category.functions.length > 0);
}

export default function functionCategoriesForSearch(query = '') {
  return filterFunctionCategories(numpyFunctionCategories, query);
}
